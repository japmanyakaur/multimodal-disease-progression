"""Step 6: dataset card (thesis Section 4.7) and model card (Section 8.11), generated from the saved results."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd  # noqa: E402

from mdp.config import RESULTS, ROOT, RUNS, TABLES, load_config  # noqa: E402


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main():
    cfg = load_config()
    s = json.load(open(RESULTS / "metrics_summary.json"))
    audit = pd.read_csv(TABLES / "table_feasibility_audit.csv")
    horizon = pd.read_csv(TABLES / "table_horizon_audit.csv")
    ext = pd.read_csv(TABLES / "table_external_cohorts.csv")
    split = pd.read_csv(TABLES / "table_split_counts.csv")
    hyp = pd.read_csv(TABLES / "table_hypotheses.csv")
    auroc = pd.read_csv(TABLES / "table_auroc_all_sets.csv")
    calib = pd.read_csv(TABLES / "table_calibration.csv")
    conf = pd.read_csv(TABLES / "table_conformal.csv")
    selected = json.load(open(RUNS / "selected_configurations.json"))

    dataset = f"""# Dataset card

Generated by `scripts/06_make_cards.py` from the saved audit tables (thesis Section 4.7).

## Source and access
* **Simulated** cohort written in the ADNIMERGE format (column names, visit codes, diagnoses,
  FreeSurfer-style volumes). No real participant data. Generator: `src/mdp/simulate.py`, seed {cfg['seed']}.
* Purpose: develop and test the pipeline before ADNI access is granted. Results describe the methods,
  not Alzheimer's disease in real people.
* Real ADNI data (if used) must stay in `data/adni/`, which git ignores.

## Generating model (summary)
Latent disease stage grows at a person-specific rate (faster for APOE-e4 carriers, accelerating with stage).
MRI atrophy becomes abnormal before cognition and daily function; education acts as cognitive reserve.
Diagnoses are noisy judgements of clinical severity. Visits follow the ADNI schedule with timing jitter,
skipped visits and informative drop-out; MRI quality ratings control measurement noise.

## Feasibility audit (development cohort)
{md_table(audit)}

## Outcome availability by horizon
{md_table(horizon)}

## Partitions (participant level)
{md_table(split)}

## External test cohorts (Stage 2, generated after the pre-registration)
{md_table(ext)}

## Known limitations
* Simulated anatomy and artefacts are schematic; 3D volumes are rendered from regional measures.
* The simulator encodes one hypothesis about disease biology; real data may differ in ways that change results.
* Volunteers in research cohorts such as ADNI differ from the general population; the simulator inherits that design.
"""
    (ROOT / "docs" / "DATASET_CARD.md").write_text(dataset)

    prop = auroc[auroc.Model.str.startswith("E5 Proposed reliability")].iloc[0]
    model = f"""# Model card: reliability-aware multimodal fusion (E5)

Generated by `scripts/06_make_cards.py` from the saved results (thesis Section 8.11).

## Intended use
Academic research on longitudinal multimodal prediction and demonstration of the research dashboard.
**Not** for diagnosis, screening, triage or treatment decisions.

## Task
Probability that a participant with MCI at the index visit is diagnosed with dementia within
{cfg['cohort']['horizon_months']} months (+/- {cfg['cohort']['tolerance_months']}). Inputs: up to
{cfg['cohort']['max_history_visits']} previous visits (MMSE, CDR-SB, ADAS-Cog13, FAQ with missingness masks and time gaps),
age, sex, education, APOE4, and five MRI-derived measures with an MRI quality rating.

## Architecture
GRU over the visit history; MLP over MRI measures (one attention token per measure); cross-attention between the
branches; reliability gate (availability-masked softmax over two modality weights); modality dropout; consistency
loss. Five-seed ensemble, temperature-scaled. Selected configuration (validation AUROC): `{json.dumps(selected['e5_proposed'])}`.

## Training data
Development partition of the simulated cohort (train split for fitting, validation split for early stopping and
selection, calibration split for temperature, threshold and conformal quantiles).

## Evaluation (AUROC, 95% participant-bootstrap CI)
| Development test (exploratory) | External A | External B |
|---|---|---|
| {prop['Development test (exploratory)']} | {prop['External A']} | {prop['External B']} |

## Pre-registered hypotheses
{md_table(hyp[hyp.Role.str.startswith('confirmatory')][['Set', 'Question', 'Comparison', 'Delta [95% CI]', 'Decision']])}

## Calibration
{md_table(calib[calib.Model.str.startswith('E5')][['Model', 'Temperature T', 'ECE after (A) [95% CI]', 'ECE after (B) [95% CI]']])}

## Uncertainty (90% conformal prediction sets, proposed model)
{md_table(conf[conf.Model.str.startswith('E5')][['Set', 'Method', 'Coverage (all)', 'Coverage (converters)', 'Coverage (non-converters)', 'Mean set size']])}

## Limitations
* Evaluated only on simulated data; external validity on real cohorts is unknown.
* Does not outperform simpler models on complete inputs in these data (see hypotheses).
* Explanations are attributions of model behaviour, not causal evidence.
"""
    (ROOT / "docs" / "MODEL_CARD.md").write_text(model)
    print("wrote docs/DATASET_CARD.md and docs/MODEL_CARD.md")


if __name__ == "__main__":
    main()
